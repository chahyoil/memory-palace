/** 사용자 수정본을 반영한 전체 사전 */
export function numberImages(overrides = {}) {
  return { ...DEFAULT_NUMBER_IMAGES, ...overrides };
}

/** 두 자리 숫자의 자음 힌트 (예: "45" → "ㄹㅁ") */
export function consonantHint(pair) {
  return CONSONANTS[+pair[0]] + CONSONANTS[+pair[1]];
}
